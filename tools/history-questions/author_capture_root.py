DOCS = {s:dict(schemaVersion=1, subject=s, reviews=[], questions=[]) for s in ('hand-memo','gyoyukron')}
NOTES = {}
for s in DOCS:
    folder = ROOT/'public/data' if s == 'hand-memo' else ROOT/'public/data/subjects'/s
    NOTES.update({n['id']:n for n in json.loads((folder/'notes.json').read_text())})
COUNTS = Counter()
def subject(page): return 'hand-memo' if page.startswith('p') else 'gyoyukron'
def captures(page):
    n = NOTES[page]
    if n.get('img'):
        src='/pages/'+n['img']
        return [dict(src=src,sha256=sha256((ROOT/'public'/src.lstrip('/')).read_bytes()).hexdigest())]
    return [{k:c[k] for k in ('src','sha256')} for c in MANIFEST[page]['captures']]
def review(page, summary, status='content', reason=None, duplicateOf=None):
    item=dict(page=page,status=status,captures=captures(page),summary=summary)
    if reason: item['reason']=reason
    if duplicateOf: item['duplicateOf']=duplicateOf
    DOCS[subject(page)]['reviews'].append(item)
def q(page, answer, prompt, quote, location, explain, aliases=(), kind='short'):
    s=subject(page); COUNTS[page]+=1
    item=dict(id=f'{s}-capture-practice-{page.replace("gyoyukron-", "")}-{COUNTS[page]}',page=page,kind=kind,prompt=prompt,
        answer=answer,acceptedAnswers=list(aliases),evidence=[dict(page=page,quote=quote)],
        captureEvidence=[dict(**captures(page)[0],quote=quote,location=location)],explain=explain,topic=NOTES[page]['title'])
    if len(quote) < 4: item['captureEvidence'][0]['quoteKind']='label'
    if kind=='cloze': item['passage']=quote
    DOCS[s]['questions'].append(item)
def cloze(page, answer, quote, location, explain, aliases=()):
    q(page,answer,quote.replace(answer,'_____',1),quote,location,explain,aliases,'cloze')

