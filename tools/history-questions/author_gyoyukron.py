def seed_evidence(seed, notes):
    result = [{'page': seed['page'], 'quote': seed['quote']}]
    expanded = {
        '교수내용지식': '• 교과의 특징적인 내용지식 구조에 대해 학습자를 고려하여 전달하는 양식이자, 학생들에게 교과를 이해하게끔 제시하고 조직하는 데 유용한 아이디어',
        '총괄적 채점': '총괄적 채점\n• 별도의 영역 구분이 필요 없음<br>• 종합적 판단',
        '분석적 채점': '분석적 채점\n• 영역을 구분<br>• 영역마다 점수 부여',
    }
    if seed['term'] in expanded:
        quote = expanded[seed['term']]
        assert quote in notes[seed['page']]['text']
        result.append({'page': seed['page'], 'quote': quote})
    if seed['term'] == '채점자 훈련':
        quote = '• 명료한 기준을 제공<br>• 일관성 있는 채점'
        assert quote in notes[seed['page']]['text']
        result.append({'page': seed['page'], 'quote': quote})
    return result


def essays(seeds, notes):
    by_term = {s['term']: s for s in seeds}
    result = []
    for index, row in enumerate(ESSAY_PLANS.strip().splitlines(), 1):
        title, prompt, *terms = row.split('|')
        selected = [by_term[t] for t in terms]
        rubric = []
        for i, s in enumerate(selected):
            maximum = (3, 3, 4)[i]
            partial = 1 if maximum == 3 else 2
            rubric.append({'id': f'r{i + 1}', 'label': s['term'], 'max': maximum,
                           'ok': s['meaning'], 'checkpoints': [s['meaning'], '문항에서 요구한 대상과 관계를 구별하여 설명한다.'],
                           'allowedScores': [0, partial, maximum],
                           'scoreLevels': [{'score': 0, 'condition': '핵심 의미가 누락되거나 다른 개념과 혼동한다.'},
                                           {'score': partial, 'condition': '핵심 의미의 일부는 맞지만 요구된 구별이나 관계 설명이 불완전하다.'},
                                           {'score': maximum, 'condition': '핵심 의미와 문항이 요구한 구별·관계를 모두 정확히 설명한다.'}],
                           'evidence': seed_evidence(s, notes)})
        skill = 'causation' if index in (14, 18) else 'source-analysis' if index in (8, 9, 12, 23, 24, 27, 28) else 'comparison'
        result.append({'id': f'{SUBJECT}-ext-essay-{index:03}', 'type': 'essay', 'skill': skill,
                       'title': title, 'prompt': prompt,
                       'answer': '\n'.join(f'{s["term"]}: {s["meaning"]}' for s in selected),
                       'explain': '각 요구를 별도 기준으로 평가한다. 명칭만 나열하지 말고 문항에서 요구한 의미와 관계를 서술한다.',
                       'evidence': list({(e['page'], e['quote']): e for c in rubric for e in c['evidence']}.values()), 'rubric': rubric})
    assert len(result) == 30
    return result


