def records():
    return [line.split('|') for line in SEEDS.strip().splitlines()]


def read_seed(row, notes):
    page, term, needle, meaning, blank = row
    nid = f'{SUBJECT}-textbook-page-{page}'
    text = notes[nid]['text']
    if needle not in text:
        raise ValueError(f'{term}: missing {needle!r} in {nid}')
    at = text.index(needle)
    start = text.rfind('\n', 0, at) + 1
    end = text.find('\n', at + len(needle))
    quote = text[start:end if end >= 0 else len(text)].strip()
    # Keep one complete sentence/HTML cell when a table row is excessively long.
    if '<br>' in quote:
        cells = quote.split('<br>')
        cell = next(c for c in cells if needle in c)
        quote = cell.strip()
    return {'term': term, 'meaning': meaning, 'page': nid, 'quote': quote, 'blank': blank}


