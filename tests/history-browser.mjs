    await store.saveAttempt({...base,value:'최종 답'});
    const unique=(await store.listAttempts()).length;
    await store.close();
    const restored=await store.loadBank(bank);
    await store.deleteAttempt('kept');
    const lateDeleted=await store.saveAttempt({...base,result:{total:10,max:10}});
    const deleted=await store.loadBank(bank);
    await store.saveAttempt({...base,id:'clear-me'});
