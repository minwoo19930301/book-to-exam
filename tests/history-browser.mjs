    const {createHistoryStore,HISTORY_TTL_MS} = await import('/src/history-store.js');
    let now=Date.now();
    const store=createHistoryStore({database:'history-transaction-tests',now:()=>now});
    const bank={subject:'hanguksa',type:'essay'};
    const base={...bank,id:'kept',questionId:'q',question:{id:'q',prompt:'질문'},value:'답',result:{total:7,max:10,items:[{id:'r',score:7}]},startedAt:now,updatedAt:now,attemptNumber:1};
